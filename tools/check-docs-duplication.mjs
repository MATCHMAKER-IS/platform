/**
 * ドキュメントの重複を検出する。
 *   node tools/check-docs-duplication.mjs
 *
 * 同じ内容が複数の資料にあると、片方だけ更新されて食い違う(実際に ../onboarding/01-setup.md のポート表が
 * 古いまま残り、既に解消した問題の記述が残っていた)。機械的に検出する。
 *
 * 検出するもの:
 *   1. 同一の見出しが複数ファイルにある(役割分担が曖昧なサイン)
 *   2. 同一の表(3行以上)が複数ファイルにある(片方が古くなる)
 *   3. 同じ URL/ポートの一覧が複数ファイルにある
 *
 * 「重複＝即悪」ではない(意図的に両方へ書くこともある)。ALLOW に理由付きで登録すれば除外できる。
 */
import { readFileSync, existsSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));

/** 検査対象(手書きの資料)。 */
/**
 * 検査するドキュメント。
 *
 * **一覧を手書きしない。**
 * `check-docs-links` が同じ形で 18 件しか見ておらず、
 * 資料の 3/4 が対象外だった(2026-08)。ここも同じ作りだったので揃える。
 *
 * 自動生成物は対象外(重複は生成側の設計の問題で、ここで指摘しても直せない)。
 */
function collectTargets() {
  const out = [];
  const walk = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.name === "node_modules") continue;
      const fp = path.join(dir, e.name);
      if (e.isDirectory()) { walk(fp); continue; }
      if (!e.name.endsWith(".md")) continue;
      const head = readFileSync(fp, "utf8").slice(0, 400);
      if (/自動生成|generated by|このファイルは.*生成/i.test(head)) continue;
      out.push(path.relative(ROOT, fp).split(path.sep).join("/"));
    }
  };
  for (const top of ["README.md", "CONTRIBUTING.md", "CLAUDE.md", "docs/HISTORY.md"]) {
    if (existsSync(path.join(ROOT, top))) out.push(top);
  }
  walk(path.join(ROOT, "docs"));
  return out;
}

const TARGETS = collectTargets();

/**
 * 許す重複の数。
 *
 * **対象を 16 → 73 ファイルに広げたときの実測値**(36 件)から、
 * ADR の定型見出しを除外して 30 件になった。
 *
 * 残るのは「docs/HISTORY.md と個別資料」の対で、
 * **一覧と詳細という役割分担**によるもの。片方に寄せると
 * 一覧から辿れなくなるため、そのままにしている。
 *
 * 減らしたら下げる。増やすときは理由を添える。
 */
const LIMIT = 30;


/** 重複していてよいもの(理由つき)。 */
const ALLOW = {
  // ── ADR の定型見出し ──────────────────────────
  // **テンプレートに沿っているだけで、重複ではない。**
  // むしろ揃っていないと、決定の背景を追いにくくなる
  // (`docs/adr/template.md` が形を定めている)
  "文脈": "ADR の定型見出し(template.md に沿う)",
  "決定": "ADR の定型見出し",
  "影響": "ADR の定型見出し",
  "理由": "ADR の定型見出し",
  "検討した代替案と見送り理由": "ADR の定型見出し",
  "状態": "ADR の定型見出し",
  // ── 以下は資料ごとに内容が違うもの ──────────────
  "確認": "各ページで独立した確認手順があるのは自然",
  "前提": "前提条件は文脈ごとに違う",
  "使い方": "対象が違えば内容も違う",
  "まとめ": "各ページの締め",
  "基本": "用語集などの汎用見出し",
  "手順": "文脈ごとに異なる",
  "トラブル": "対象が違う",
  "次に読むもの": "各ページからの導線として妥当",
  "チェックリスト": "対象(AI のコード / 新規アプリ)が違う",
  "検証": "文脈ごとに異なる(CLAUDE.md は規約文脈・COMMANDS.md は早見表)",
  "開発ルール": "README は要点のみ・詳細は CLAUDE.md(導線として意図的)",
  "よく使うコマンド": "README は導線のみ・一覧は COMMANDS.md(意図的)",
  "リファレンスサイト": "docs/README は案内・SETUP は生成手順(役割が違う)",
  "クイックスタート": "README は最短手順・SETUP は詳細(導線あり)",
  "開発サーバ": "CLAUDE.md は AI/開発者向けの規約文脈・COMMANDS.md は早見表(役割が違う)",
  "データベース": "同上",
  // **`"検証"` はここにも書かれていたが、上の定義と重複していた**(2026-08 に統合)。
  // オブジェクトなので後の値が前を静かに上書きし、**先に書いた理由が消えていた**。
  // 除外の理由が消えると、次の人は「なぜ許しているのか」を調べ直すことになる。
  "生成物": "同上",
  "書き方": "対象(コミットメッセージ / テスト)が違う",
  "実行": "対象が違う汎用見出し",
  "メールが届かない": "開発時(Mailpit)と本番時(SMTP設定)で対処が違う",
};

/** 見出しを集める(## 以下)。 */
function collectHeadings(body) {
  const out = [];
  for (const m of body.matchAll(/^#{2,4}\s+(.+)$/gm)) {
    const raw = (m[1] ?? "").trim();
    // 番号・記号を除いて正規化(「## 1. ツールを入れる」→「ツールを入れる」)
    const norm = raw.replace(/^[\d.\s]+/, "").replace(/[（(].*?[）)]/g, "").replace(/\s+/g, "").trim();
    if (norm) out.push({ raw, norm });
  }
  return out;
}

/** 表(| で始まる行が3行以上続くブロック)を集める。 */
function collectTables(body) {
  const tables = [];
  let current = [];
  for (const line of body.split("\n")) {
    if (line.trim().startsWith("|")) {
      current.push(line.trim());
    } else {
      if (current.length >= 3) tables.push(current.join("\n"));
      current = [];
    }
  }
  if (current.length >= 3) tables.push(current.join("\n"));
  return tables;
}

export function check() {
  const files = TARGETS.filter((f) => existsSync(path.join(ROOT, f)));
  const headingMap = new Map(); // norm -> [{file, raw}]
  const tableMap = new Map(); // 表の内容 -> [file]

  for (const rel of files) {
    const body = readFileSync(path.join(ROOT, rel), "utf8");
    // **ADR は同じ見出しを使うのが正しい形式。**
    // 「背景」「決定」「結果」「ステータス」を全 ADR が持つのは**揃っている証拠**で、
    // 重複ではない——数えると**正しい形式ほど違反が増える**ことになる。
    // 本文の重複は引き続き見る(見出しだけ対象外)。
    if (rel.replace(/\\/g, "/").startsWith("docs/adr/")) continue;
    for (const h of collectHeadings(body)) {
      if (!headingMap.has(h.norm)) headingMap.set(h.norm, []);
      headingMap.get(h.norm).push({ file: rel, raw: h.raw });
    }
    for (const t of collectTables(body)) {
      // 表の中身だけで比較(見出し行の差は無視)
      const key = t.replace(/\s+/g, "");
      if (key.length < 80) continue; // 小さい表は除外(誤検出が多い)
      if (!tableMap.has(key)) tableMap.set(key, []);
      tableMap.get(key).push(rel);
    }
  }

  const issues = [];

  // 1. 同一見出し
  for (const [norm, list] of headingMap) {
    if (list.length < 2) continue;
    if (Object.keys(ALLOW).some((a) => norm.includes(a.replace(/\s+/g, "")))) continue;
    const uniqueFiles = [...new Set(list.map((l) => l.file))];
    if (uniqueFiles.length < 2) continue; // 同じファイル内の重複は対象外
    issues.push({
      kind: "見出し",
      message: `「${list[0].raw}」が ${uniqueFiles.length} ファイルにあります: ${uniqueFiles.join(", ")}`,
    });
  }

  // 2. 同一の表
  for (const [, list] of tableMap) {
    const uniqueFiles = [...new Set(list)];
    if (uniqueFiles.length < 2) continue;
    issues.push({
      kind: "表",
      message: `同じ内容の表が ${uniqueFiles.length} ファイルにあります: ${uniqueFiles.join(", ")}（片方が古くなります）`,
    });
  }

  // **見出しの重複は返さない。** 「Windows」「環境変数」が複数の資料に出るのは
  // **当然**で、数えると**丁寧に書くほど違反が増える**
  // ——2026-08 に入門資料を統合したとき、見出しだけで 60 件になった。
  // **危ないのは本文の重複**（片方だけ更新されて食い違う）。
  // 参考として `headings` に件数だけ入れる。
  const headings = issues.filter((i) => i.kind === "見出し").length;
  return { files: files.length, issues: issues.filter((i) => i.kind !== "見出し"), headings };
}

function main() {
  const { files, issues } = check();
  if (issues.length === 0) {
    console.log(`✅ ドキュメントに気になる重複はありません(${files} ファイル検査)`);
    return;
  }
  for (const i of issues) console.warn(`⚠️  [${i.kind}] ${i.message}`);
  // **見出しは数えない**(「Windows」「環境変数」が複数に出るのは当然で、
  // 数えると**丁寧に書くほど違反が増える**)。危ないのは本文の重複
  const headingCount = issues.filter((i) => i.kind === "見出し").length;
  console.warn(`\n${issues.length - headingCount} 件（本文）。重複が意図的なら問題ありませんが、`);
  console.warn("「片方だけ更新されて食い違う」事故が起きやすい箇所です。");
  console.warn("役割分担を見直すか、片方に寄せて相互リンクにすることを検討してください。");
  console.warn(`（見出しの重複 ${headingCount} 件は数えていません——同じ話題が複数に出るのは当然です）`);

  // **増える方向にだけ効かせる。**
  // 重複が常に悪いわけではない(README とセットアップ手順など、
  // 入口を分ける意図のものもある)ので、既存分は許す。
  // ただし**増えたら止める** — 気づかないうちに食い違う箇所が広がる
  // **見出しの重複は数えない。** 「Windows」「環境変数」のような見出しが
  // 複数の資料に出るのは**当然**で、数えると**丁寧に書くほど違反が増える**
  // ——2026-08 に入門資料を統合したとき、見出しだけで 60 件になった。
  //
  // **危ないのは本文の重複**（片方だけ更新されて食い違う）なので、
  // そちらを上限で管理する。見出しは参考情報として出すだけ。
  const bodyIssues = issues.filter((i) => i.kind !== "見出し");
  if (bodyIssues.length > LIMIT) {
    console.error(`\n❌ 重複が ${bodyIssues.length} 件に増えました(上限 ${LIMIT})。`);
    console.error("   片方に寄せて相互リンクにするか、上限を上げる理由を添えてください。");
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
