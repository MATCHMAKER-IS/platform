/**
 * ドキュメントが「実在しないもの」を案内していないか検査する。
 *   node tools/check-docs-links.mjs
 *
 * 初心者向けガイドで最も困るのは、書いてあるとおりにやったのに動かないこと。
 * 原因の多くは「コマンド名が変わった」「ファイルが移動した」といった単純なズレで、
 * 人のレビューでは見落とされる。ここで機械的に検出する。
 *
 * 検査対象(手書きドキュメント。自動生成物は check-generated の担当):
 *   1. `pnpm xxx` が package.json に実在するか
 *   2. Markdown の内部リンク先が実在するか
 *   3. 参照するファイルパス(`docs/...` `apps/...` 等)が実在するか
 */
import { readFileSync, existsSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));

/** 検査するドキュメント(手書きのもの)。自動生成物は対象外。 */
/**
 * 検査するドキュメント。
 *
 * **一覧を手書きしない。**
 * 以前は 18 件を手で並べており、`docs/` の手書き 69 件のうち
 * **51 件がリンク切れを検出できない**状態だった(2026-08 に気づいた)。
 *
 * 自動生成物は対象外(生成側を直すべきで、ここで指摘しても直せない)。
 */
function collectTargets() {
  const out = [];
  const walk = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.name === "node_modules") continue;
      const fp = path.join(dir, e.name);
      if (e.isDirectory()) { walk(fp); continue; }
      if (!e.name.endsWith(".md")) continue;
      const head = readFileSync(fp, "utf8").slice(0, 400);
      // **自動生成物は飛ばす。** 生成側を直す
      if (/自動生成|generated by|このファイルは.*生成/i.test(head)) continue;
      out.push(path.relative(ROOT, fp).split(path.sep).join("/"));
    }
  };
  for (const top of ["README.md", "CONTRIBUTING.md", "CLAUDE.md", "docs/HISTORY.md"]) {
    if (existsSync(path.join(ROOT, top))) out.push(top);
  }
  walk(path.join(ROOT, "docs"));
  return out;
}

const TARGETS = collectTargets();


/** pnpm の組み込みコマンド(package.json に無くて当然)。 */
const PNPM_BUILTIN = new Set(["install", "add", "remove", "why", "outdated", "exec", "run", "dlx", "up", "list", "store", "config", "filter"]);
/** 説明文で使うプレースホルダ(実在しなくて当然)。 */
const PLACEHOLDERS = new Set(["xxx", "name", "cmd"]);

export function check() {
  const pkg = JSON.parse(readFileSync(path.join(ROOT, "package.json"), "utf8"));
  const scripts = new Set(Object.keys(pkg.scripts ?? {}));
  const issues = [];
  let scanned = 0;

  // 0. package.json のコマンドが実在するファイルを指しているか。
  //    「実行すると必ず失敗する」コマンドは、打つまで気づけない(実際に gen:depgraph が壊れていた)
  for (const [name, body] of Object.entries(pkg.scripts ?? {})) {
    for (const m of String(body).matchAll(/(?:tools|scripts)\/[\w./-]+\.(?:mjs|mts|ts|sh|ps1)/g)) {
      if (!existsSync(path.join(ROOT, m[0]))) {
        issues.push(`package.json: \`pnpm ${name}\` が存在しないファイルを指しています → ${m[0]}`);
      }
    }
  }

  for (const rel of TARGETS) {
    const file = path.join(ROOT, rel);
    if (!existsSync(file)) {
      issues.push(`${rel}: ファイルがありません(TARGETS の指定ミス?)`);
      continue;
    }
    scanned += 1;
    const body = readFileSync(file, "utf8");
    const dir = path.dirname(file);

    // 1. pnpm コマンドの実在
    // ハイフンも拾う(gen:portal-reference / version-packages 等)。
    // 入れないと `pnpm gen:portal-reference` を "gen:portal" と誤読して「存在しない」と言う。
    for (const m of body.matchAll(/`pnpm ([a-z][a-z0-9:-]*)\b/g)) {
      const cmd = m[1];
      if (!cmd || PNPM_BUILTIN.has(cmd) || PLACEHOLDERS.has(cmd)) continue;
      // pnpm --filter xxx のような形は除外
      if (cmd === "filter") continue;
      if (!scripts.has(cmd)) issues.push(`${rel}: \`pnpm ${cmd}\` は package.json に存在しません`);
    }

    // 2. Markdown 内部リンク(相対パスの .md)
    for (const m of body.matchAll(/\]\(([^)]+\.md)(?:#[^)]*)?\)/g)) {
      const link = m[1];
      if (!link || link.startsWith("http")) continue;
      const target = path.resolve(dir, link);
      if (!existsSync(target)) issues.push(`${rel}: リンク切れ → ${link}`);
    }

    // 3. コード内で言及するリポジトリ内パス(バッククォート囲み)。
    //    ただし「これから作るもの」「例示」「MCP のメソッド名」は実在しなくて当然なので除外する。
    for (const m of body.matchAll(/`((?:docs|apps|packages|tools|scripts|demos)\/[A-Za-z0-9_./-]+)`/g)) {
      const p = m[1];
      if (!p) continue;
      if (p.includes("<") || p.includes("*")) continue;          // プレースホルダ
      if (/\bmy-app\b|\bmy-feature\b|\bsetup-guide\b/.test(p)) continue;  // 手順書の例示
      // **「読み手がこれから作るファイル」は実在しなくて当然。**
      // 除外を仮の名前(my-app 等)の一覧で持つと、実名で書く手順書
      // ——課題や雛形のコピー手順——が書けない。実際 2026-08 に
      // ONBOARDING_TASK が「このファイルを新しく作る」と書けずに落ちた。
      // 名前ではなく**同じ行の言い回し**で判定する。
      const line = body.slice(0, m.index).split("\n").length - 1;
      if (/新しく作る|新規作成|これから作る|作成してください/.test(body.split("\n")[line] ?? "")) continue;
      if (/^tools\/(list|call)$/.test(p)) continue;              // MCP のメソッド名(パスではない)
      if (!p.includes("/") || !/\.(ts|tsx|mts|mjs|md|json|ps1|sh|yml)$|\/$/.test(p)) {
        // 拡張子もスラッシュ終端も無いものはパスとは限らない(例: tools/list)
        if (!existsSync(path.join(ROOT, p))) continue;
      }
      if (!existsSync(path.join(ROOT, p))) {
        issues.push(`${rel}: 参照先がありません → ${p}`);
      }
    }

    // **コード表記のパスも見る。**
    // `[名前](パス)` のリンクだけだと、`` `e2e/xxx.spec.ts` `` の
    // ような書き方が素通りする
    issues.push(...checkCodePaths(rel, body));
  }
  return { scanned, issues };
}

/**
 * 資料が **`` `apps/...` `` の形で指すファイル**が実在するか。
 *
 * 【なぜリンクと別に見るか】
 * Markdown のリンク(`[名前](パス)`)は既に見ているが、
 * **コード表記で書かれたパスは素通り**していた。
 * 「`e2e/equipment-app.spec.ts` を見てください」と書いてあって
 * 実際には無い、という状態が起きる(2026-08 に 1 件見つかった)。
 *
 * `my-app` のような**例示は対象外**(手順書が仮の名前を使う)。
 *
 * @param rel 資料のパス
 * @param body 中身
 * @returns 見つからなかったパスの一覧
 */
function checkCodePaths(rel, body) {
  const out = [];
  const lines = body.split("\n");
  // **パッケージ名も見る。**
  // `@platform/xxx` と書いて実在しないと、探して見つからない。
  // ただし日本語が続く場合(`@platform/mailがトップ`)は抽出の誤りなので、
  // **区切り(バッククォート・空白・句読点)で終わるものだけ**を対象にする
  for (const [i, line] of lines.entries()) {
    for (const m of line.matchAll(/`(@platform\/[a-z][\w-]*)`/g)) {
      const name = m[1];
      if (/xxx|<[^>]+>/.test(name)) continue;
      const dir = path.join(ROOT, "packages", name.slice("@platform/".length));
      if (existsSync(dir)) continue;
      out.push(`${rel}:${i + 1}: パッケージがありません → ${name}`);
    }
  }
  for (const [i, line] of lines.entries()) {
    for (const m of line.matchAll(/`((?:apps|packages|tools|e2e)\/[\w./-]+\.(?:ts|tsx|mjs|prisma))`/g)) {
      const target = m[1];
      // **例示は飛ばす。** 手順書は仮の名前を使う
      if (/my-app|<[^>]+>|xxx|例:/.test(target)) continue;
      // **読み手がこれから作るファイルも飛ばす**(上のパスと同じ判定)。
      // 片方だけ直すと、同じ記述が検出のされ方によって通ったり落ちたりする。
      if (/新しく作る|新規作成|これから作る|作成してください/.test(line)) continue;
      if (existsSync(path.join(ROOT, target))) continue;
      out.push(`${rel}:${i + 1}: 参照先がありません → ${target}`);
    }
  }
  return out;
}

function main() {
  const { scanned, issues } = check();
  if (issues.length === 0) {
    console.log(`✅ ドキュメントの参照はすべて有効(${scanned} ファイル検査)`);
    return;
  }
  for (const i of issues) console.error(`❌ ${i}`);
  console.error(`\n${issues.length} 件。書いてあるとおりにやって動かないと初心者が詰まります。修正してください。`);
  process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
